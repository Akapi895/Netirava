"""Experiment registry: scans runs/*/run.json and model metadata and writes
registry.md and registry.json in the configured runs directory. Nothing is
recomputed; every row points at the artifact that holds it. Runs created
before git_commit was stored get the latest commit preceding their creation
time, marked "(inferred)"."""

import json
import os
import subprocess
from pathlib import Path

import pandas as pd

from netirava import config as K


def _git(*args):
    try:
        return subprocess.check_output(["git", *args], cwd=K.ROOT, text=True, stderr=subprocess.DEVNULL).strip()
    except Exception:
        return ""


def _commit_before(iso):
    c = _git("rev-list", "-1", f"--before={iso}", "HEAD")
    if c:
        return c[:7] + " (inferred)"
    first = _git("rev-list", "--max-parents=0", "HEAD")
    return (first[:7] + " (run predates first commit; code committed there)") if first else "?"


def _path_reference(target, base):
    """Portable relative path, or a file URI when Windows drives differ."""
    try:
        return os.path.relpath(target, base).replace("\\", "/")
    except ValueError:
        return Path(target).resolve().as_uri()


def build(cfg):
    runs_dir = K.path(cfg, "runs")
    rows = []
    for rj in sorted(runs_dir.glob("*/run.json")):
        m = json.loads(rj.read_text(encoding="utf-8"))
        d = rj.parent
        files = [f for f in ("EVALUATION.json", "DECISIONS_dev.json", "DECISIONS_holdout.json", "DECISIONS_holdout_triage.json",
                             "FAMILY_REPORT.json") if (d / f).exists()]
        rows.append({"run_id": m["run_id"], "mode": m["mode"], "pace": m.get("pace"), "model_dir": m["a0"].get("model_dir", "a0"),
                     "a0_model": m["a0"]["model_hash"], "classes": len(m["a0"]["classes"]),
                     "anomaly_model": (m.get("anomaly") or {}).get("model_hash"), "threshold": round(m["a0"]["threshold"], 6),
                     "segments": ",".join(m.get("segments", [])), "events": m["events"],
                     "holdout": bool(m.get("unlock_holdout")), "feature_schema": m.get("feature_schema_hash"),
                     "config_sha1": m["config_sha1"][:10], "manifest_sha1": m["manifest_sha1"][:10],
                     "git_commit": (m.get("git_commit") or "")[:7] or _commit_before(m["created_wall_utc"]),
                     "family_fields": "stored" if "family" in m else "computed at load",
                     "active_decisions_sha1": m.get("active_decisions_sha1", "")[:10], "evaluations": ",".join(files)})
    models = []
    for mj in sorted((K.path(cfg, "models")).glob("**/a0_meta.json")):
        m = json.loads(mj.read_text(encoding="utf-8"))
        models.append({"path": _path_reference(mj.parent, K.ROOT), "model_hash": m["model_hash"], "variant": m.get("variant", "a0"),
                       "seed": m.get("seed", (m.get("resolved_params") or {}).get("random_seed")),
                       "classes": len(m["classes"]), "labels": m.get("labels", "truth.parquet (original NF-v3)"),
                       "threshold": round(m["threshold"]["value"], 6)})
    for mj in sorted((K.path(cfg, "models").parent).glob("models*/anomaly/anomaly_meta.json")):
        m = json.loads(mj.read_text(encoding="utf-8"))
        models.append({"path": _path_reference(mj.parent, K.ROOT), "model_hash": m["model_hash"], "variant": "anomaly (IsolationForest)",
                       "seed": m["params"]["random_state"], "classes": None, "labels": "train benign (original)",
                       "threshold": round(m["threshold"]["value"], 6)})
    rdf, mdf = pd.DataFrame(rows), pd.DataFrame(models)
    out = {"runs": rows, "models": models, "head": _git("rev-parse", "--short", "HEAD")}
    runs_dir.mkdir(parents=True, exist_ok=True)
    (runs_dir / "registry.json").write_text(json.dumps(out, indent=2, default=str), encoding="utf-8")
    context = _path_reference(K.ROOT / "docs" / "experiment_registry.md", runs_dir)
    md = ["# Experiment registry (generated)", "",
          f"Generated by `python -m netirava registry` at git `{out['head']}`. Do not edit by hand; curated context is in "
          f"[curated experiment history]({context}).", "", "## Replay runs (configured runs directory)", "",
          rdf.to_markdown(index=False), "", "## Models (`artifacts/`)", "", mdf.to_markdown(index=False), ""]
    p = runs_dir / "registry.md"
    p.write_text("\n".join(md), encoding="utf-8")
    return {"runs": len(rows), "models": len(models), "file": str(p)}
