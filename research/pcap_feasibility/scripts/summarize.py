"""Summarise results/*.json into results/SUMMARY.md (tables used by the reports)."""
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
R = ROOT / "results"
SHORT = {"CTU-IoT-Malware-Capture-34-1": "34-1 Mirai", "CTU-IoT-Malware-Capture-8-1": "8-1 Hakai",
         "CTU-IoT-Malware-Capture-20-1": "20-1 Torii"}


def flat(rows):
    out = []
    for r in rows:
        d = {k: r[k] for k in ("test_capture", "variant", "seed", "n_features", "pr_auc", "roc_auc", "fit_seconds",
                               "infer_us_per_flow", "n_cal_benign", "n_test_benign", "n_test_mal")}
        for lvl in ("fpr0.01", "fpr0.001"):
            m = r[lvl]
            for k in ("recall", "precision", "f1", "fpr", "fp", "tp", "false_incidents", "incidents",
                      "oracle_recall_at_test_fpr"):
                d[f"{lvl}_{k}"] = m[k]
            d[f"{lvl}_support"] = f"cal {m['support']['calibration']} / test {m['support']['test']}"
            for fam, v in m["per_family"].items():
                d[f"{lvl}_fam_{fam}"] = v["recall"]
            ex = r.get(f"{lvl}_excl_zero_pkt_records")
            if ex:
                d[f"{lvl}_excl0_recall"] = ex["recall"]
                d[f"{lvl}_excl0_pr_auc"] = ex["pr_auc"]
                d[f"{lvl}_excl0_n_excluded"] = ex["n_excluded"]
                for fam, v in ex["per_family"].items():
                    d[f"{lvl}_excl0_fam_{fam}"] = v["recall"]
        out.append(d)
    df = pd.DataFrame(out)
    df["test"] = df["test_capture"].map(SHORT)
    return df


def ms(s):
    s = s.dropna()
    if s.empty:
        return "—"
    return f"{s.mean():.3f} ± {s.std(ddof=0):.3f}" if len(s) > 1 else f"{s.mean():.3f}"


def main():
    lines = ["# RQ-PCAP results summary (auto-generated by scripts/summarize.py)", ""]
    df = flat(json.loads((R / "loco_main.json").read_text(encoding="utf-8")))
    order = ["A", "B", "C", "A_plus_noise", "A_plus_permuted_B"]
    lines += ["## LOCO binary, mean ± sd over 3 seeds (threshold locked on calibration benign of training captures)", "",
              "| Test capture | Set | #feat | PR-AUC | ROC-AUC | Recall @cal-1% | Test FPR @cal-1% | Precision @cal-1% | F1 @cal-1% | False incidents @cal-1% | Oracle recall @test-FPR 1% | Oracle recall @test-FPR 0.1% | Recall @cal-0.1% | Test FPR @cal-0.1% |",
              "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for t in SHORT.values():
        for v in order:
            g = df[(df.test == t) & (df.variant == v)]
            if g.empty:
                continue
            lines.append(f"| {t} | {v} | {int(g.n_features.iloc[0])} | {ms(g.pr_auc)} | {ms(g.roc_auc)} | {ms(g['fpr0.01_recall'])} | "
                         f"{ms(g['fpr0.01_fpr'])} | {ms(g['fpr0.01_precision'])} | {ms(g['fpr0.01_f1'])} | {ms(g['fpr0.01_false_incidents'])} | "
                         f"{ms(g['fpr0.01_oracle_recall_at_test_fpr'])} | {ms(g['fpr0.001_oracle_recall_at_test_fpr'])} | "
                         f"{ms(g['fpr0.001_recall'])} | {ms(g['fpr0.001_fpr'])} |")
    lines += ["", "Support:"]
    for t in SHORT.values():
        g = df[(df.test == t) & (df.variant == "A")].iloc[0]
        lines.append(f"- {t}: test benign {g.n_test_benign}, test malicious {g.n_test_mal}, calibration benign {g.n_cal_benign}; "
                     f"1%: {g['fpr0.01_support']}; 0.1%: {g['fpr0.001_support']}")

    lines += ["", "## Paired deltas (same seed): C − A and controls − A", "",
              "| Test | Metric | C − A (per seed) | B − A | (A+noise) − A | (A+perm B) − A | C − (A+perm B) |", "|---|---|---|---|---|---|---|"]
    for t in SHORT.values():
        for met in ("pr_auc", "fpr0.01_recall", "fpr0.01_fpr", "fpr0.01_oracle_recall_at_test_fpr"):
            p = df[df.test == t].pivot(index="seed", columns="variant", values=met)
            f = lambda a, b: ", ".join(f"{x:+.3f}" for x in (p[a] - p[b]).to_numpy()) if {a, b} <= set(p.columns) else "—"
            lines.append(f"| {t} | {met} | {f('C', 'A')} | {f('B', 'A')} | {f('A_plus_noise', 'A')} | {f('A_plus_permuted_B', 'A')} | {f('C', 'A_plus_permuted_B')} |")

    lines += ["", "## Per-family recall at the calibration-locked 1% threshold (mean over seeds)", "",
              "| Test | Family | A | B | C | A+perm B |", "|---|---|---|---|---|---|"]
    for t in SHORT.values():
        g = df[df.test == t]
        for c in [c for c in g.columns if c.startswith("fpr0.01_fam_")]:
            vals = {v: g[g.variant == v][c].mean() for v in ("A", "B", "C", "A_plus_permuted_B")}
            lines.append(f"| {t} | {c.replace('fpr0.01_fam_', '')} | " + " | ".join(f"{vals[v]:.3f}" for v in ("A", "B", "C", "A_plus_permuted_B")) + " |")
    ex = df[df["fpr0.01_excl0_recall"].notna()] if "fpr0.01_excl0_recall" in df else pd.DataFrame()
    if not ex.empty:
        lines += ["", f"## Sensitivity: excluding Zeek records with 0 packets (n excluded = {int(ex['fpr0.01_excl0_n_excluded'].iloc[0])}, all on 34-1)", "",
                  "| Set | PR-AUC | Recall @cal-1% | DDoS recall |", "|---|---|---|---|"]
        for v in order:
            g = ex[ex.variant == v]
            lines.append(f"| {v} | {ms(g['fpr0.01_excl0_pr_auc'])} | {ms(g['fpr0.01_excl0_recall'])} | {ms(g.get('fpr0.01_excl0_fam_DDoS', pd.Series(dtype=float)))} |")

    abl = flat(json.loads((R / "loco_ablation_groups.json").read_text(encoding="utf-8")))
    base = df[(df.variant == "C") & (df.seed == 0)].set_index("test")
    lines += ["", "## Leave-one-B-group-out ablation (seed 0; Δ vs full C seed 0) — EXPLORATORY", "",
              "| Removed group | " + " | ".join(f"{t} ΔPR-AUC / ΔRecall@1%" for t in SHORT.values()) + " |", "|---|---|---|---|"]
    for v in sorted(abl.variant.unique()):
        cells = []
        for t in SHORT.values():
            g = abl[(abl.variant == v) & (abl.test == t)]
            cells.append(f"{g.pr_auc.iloc[0] - base.loc[t, 'pr_auc']:+.3f} / {g['fpr0.01_recall'].iloc[0] - base.loc[t, 'fpr0.01_recall']:+.3f}")
        lines.append(f"| {v.replace('C_minus_', '')} | " + " | ".join(cells) + " |")

    raw = json.loads((R / "loco_main.json").read_text(encoding="utf-8"))
    lines += ["", "## Top-10 feature importance (seed 0)", ""]
    for r in raw:
        if r["seed"] == 0 and r["variant"] in ("A", "C") and "top_features" in r:
            lines.append(f"- {SHORT[r['test_capture']]} / {r['variant']}: " + ", ".join(f"{k} {v}" for k, v in r["top_features"].items()))

    ci = json.loads((R / "capture_identifiability.json").read_text(encoding="utf-8"))["benign_only"]
    lines += ["", "## Capture identifiability on benign flows (5-fold CV, 3 captures; chance = 0.333)", "",
              "| Set | macro-F1 | accuracy |", "|---|---|---|"]
    for k, v in ci.items():
        lines.append(f"| {k} | {v['macro_f1']:.3f} | {v['accuracy']:.3f} |")

    mc = json.loads((R / "within_capture_multiclass_EXPLORATORY.json").read_text(encoding="utf-8"))
    runs = pd.DataFrame(mc["runs"])
    lines += ["", "## Within-capture temporal split, multiclass — EXPLORATORY", "",
              f"Scored classes: {mc['scored_classes']}; not scored (support < 20 in train or test): {mc['not_scored']}", "",
              "| Set | macro-F1 | " + " | ".join(f"F1 {c}" for c in mc["scored_classes"]) + " | benign FPR (argmax) |",
              "|---|---|" + "---|" * len(mc["scored_classes"]) + "---|"]
    for s, g in runs.groupby("set"):
        pcs = [ms(pd.Series([r[c] for r in g.per_class_f1])) for c in mc["scored_classes"]]
        lines.append(f"| {s} | {ms(g.macro_f1)} | " + " | ".join(pcs) + f" | {ms(g.benign_fpr)} |")

    lines += ["", "## Cost", "", "| Set | fit s (mean) | inference µs/flow (mean) |", "|---|---|---|"]
    for v in order:
        g = df[df.variant == v]
        lines.append(f"| {v} | {g.fit_seconds.mean():.2f} | {g.infer_us_per_flow.mean():.2f} |")
    (R / "SUMMARY.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    sys.stdout.reconfigure(encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
